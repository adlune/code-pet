const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  setIgnore: (ignore) => ipcRenderer.send('set-ignore', ignore),
  setMetrics: (m) => ipcRenderer.send('metrics', m),
  onEdges: (cb) => ipcRenderer.on('edges', (_e, d) => cb(d)),
  moveBy: (dx, dy) => ipcRenderer.invoke('move-by', dx, dy),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  showMenu: () => ipcRenderer.send('show-menu'),
  onEvent: (cb) => ipcRenderer.on('pet-event', (_e, d) => cb(d)),
  onSessions: (cb) => ipcRenderer.on('sessions', (_e, d) => cb(d)),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, d) => cb(d)),
  onFall: (cb) => ipcRenderer.on('fall', () => cb()),
  // the optional local AI assistant (src/assistant): the prompt bar, answers and Allow/Deny
  askSubmit: (q) => ipcRenderer.send('ask-submit', q),
  askClose: () => ipcRenderer.send('ask-close'),
  askCancel: () => ipcRenderer.send('ask-cancel'),
  onAskOpen: (cb) => ipcRenderer.on('ask-open', (_e, d) => cb(d)),
  onAskMode: (cb) => ipcRenderer.on('ask-mode', (_e, d) => cb(d)),
  onAskStart: (cb) => ipcRenderer.on('ask-start', (_e, d) => cb(d)),
  onAskStream: (cb) => ipcRenderer.on('ask-stream', (_e, d) => cb(d)),
  onAskEnd: (cb) => ipcRenderer.on('ask-end', (_e, d) => cb(d)),
  onAskNotice: (cb) => ipcRenderer.on('ask-notice', (_e, d) => cb(d)),
  onAskConfirm: (cb) => ipcRenderer.on('ask-confirm', (_e, d) => cb(d)),
  onAskConfirmClose: (cb) => ipcRenderer.on('ask-confirm-close', (_e, d) => cb(d)),
  confirmReply: (cid, allow) => ipcRenderer.send('confirm-reply', { cid, allow }),
  confirmKey: (allow) => ipcRenderer.send('confirm-key', allow),
  undoEdit: (id) => ipcRenderer.invoke('undo-edit', id),
  bubbleRect: (r) => ipcRenderer.send('bubble-rect', r),
  copyText: (text) => ipcRenderer.send('copy-text', text),
});
